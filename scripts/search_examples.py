"""Generate docs/search-examples.md: top hits per search mode for the example queries.

Needs the index (`uv run regulatory-helper index`). Usage: uv run python scripts/search_examples.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from eval_queries import QUERIES, is_hit  # noqa: E402

from regulatory_helper import retrieval  # noqa: E402

DOC = Path(__file__).resolve().parents[1] / "docs" / "search-examples.md"
EXAMPLES = [0, 1, 2, 3, 4, 5, 6, 8, 11, 12]  # indices into QUERIES: 4 reference style, 6 content style

r = retrieval.Retriever.load()
out = ["# Search examples (Section 2)\n",
       f"Model: `{r.model_name}`, k = 6. Generated by `scripts/search_examples.py`.\n",
       "A check mark means the chunk is one of the expected chunks for the query (see `scripts/eval_queries.py`). "
       "Queries 1 to 4 ask for a concrete reference, 5 to 10 are content questions. "
       "The queries are English, as the query rewriting of section 3 will produce them.\n"]
for n, idx in enumerate(EXAMPLES, 1):
    q, gold = QUERIES[idx]
    out.append(f"## {n}. {q}\n\nExpected: {', '.join(f'`{g}`' for g in gold)}\n")
    out.append("| Rank | bm25 | vector | hybrid |\n|---|---|---|---|")
    cols = {m: r.search(q, mode=m, k=6) for m in retrieval.MODES}
    for rank in range(6):
        row = []
        for m in retrieval.MODES:
            h = cols[m][rank] if rank < len(cols[m]) else None
            row.append("" if h is None else f"{'✓ ' if is_hit(h.chunk.id, gold) else ''}`{h.chunk.id}`")
        out.append(f"| {rank + 1} | " + " | ".join(row) + " |")
    out.append("")

# summary over all queries
out.append("## Summary over all 16 queries\n")
out.append("| Mode | hit@6 | MRR@6 |\n|---|---|---|")
for m in retrieval.MODES:
    hit = rr = 0.0
    for q, gold in QUERIES:
        ranks = [h.rank for h in r.search(q, mode=m, k=6) if is_hit(h.chunk.id, gold)]
        hit += bool(ranks)
        rr += 1 / ranks[0] if ranks else 0
    out.append(f"| {m} | {hit / len(QUERIES):.2f} | {rr / len(QUERIES):.3f} |")
out.append("\nThis is a small hand-made set for orientation, not the validation of section 5.\n")
DOC.write_text("\n".join(out), encoding="utf-8")
print("wrote", DOC)
