"""Generate docs/chunking.md (statistics + random samples) from data/processed/chunks.jsonl.

Usage: uv run python scripts/chunk_report.py
"""
import random
import re
import statistics
from collections import Counter
from pathlib import Path

from regulatory_helper import chunking

DOC = Path(__file__).resolve().parents[1] / "docs" / "chunking.md"

HEAD = """# Chunking (Section 1b)

`uv run regulatory-helper ingest` reads `data/raw/*.xhtml` and writes `data/processed/chunks.jsonl`
(one JSON object per line, generated by `scripts/chunk_report.py` together with this file).

## Sources and decisions
- Format: XHTML (decision taken as recommended in `data-format.md`).
- Articles and annexes: MDR from the consolidated version (2026-01-01), GDPR and AI Act from the OJ text.
- Recitals: included and flagged `type=recital`. MDR recitals come from the original 2017 act because
  the consolidated text has none; their citation says so.

## Fields
| Field | Meaning |
|---|---|
| `id` | Stable, unique ID (scheme below) |
| `law` | `MDR`, `GDPR` or `AIACT` |
| `type` | `article`, `annex` or `recital` |
| `article` | Article number (`10`, `10a`), annex name (`ANNEX VIII`) or `null` for recitals |
| `title` | Article title; for annexes `Annex VIII: <annex title> > <chapter> > <section> > <rule>`; for recitals `Recital 4` |
| `paragraph` | Paragraph number (`9`), definition number (`(3)`), annex point (`6.3`), `intro` or recital number |
| `text` | Original wording of this chunk only (paragraph numbers removed, lists kept as indented lines) |
| `source_url` | EUR-Lex document URL with the element anchor (`#art_10`). Anchors are best effort, not verified |
| `citation` | Human readable citation, e.g. `MDR Art. 10(9)`, used later for the sources list |

`Chunk.contextual_text()` returns `citation - title` followed by the text. This is the string to embed
in section 2 (the architecture asks for law, article number and title in front of the paragraph).

## ID scheme
| Kind | Pattern | Example |
|---|---|---|
| Article paragraph | `<LAW>-<article>-<paragraph>` | `MDR-10-9`, `GDPR-9-2` |
| Article without numbered paragraphs | `<LAW>-<article>` | `MDR-7` |
| Lead-in before paragraph 1 | `<LAW>-<article>-intro` | |
| Definition | `<LAW>-<article>-<n>` | `MDR-2-1`, `GDPR-4-1` |
| Annex point | `<LAW>-ANNEX-<numeral>-<point>` | `MDR-ANNEX-VIII-6.3` (Rule 11), `AIACT-ANNEX-III-5` |
| Annex introduction | `<LAW>-ANNEX-<numeral>-intro` | `AIACT-ANNEX-III-intro` |
| Unnumbered annex section | `<LAW>-ANNEX-<numeral>-n<k>` | `MDR-ANNEX-VI-n3` |
| Recital | `<LAW>-REC-<n>` | `GDPR-REC-4` |
| Split part (any kind) | `<id>-s<k>` | `MDR-10-9-s2` |

Collisions (same point number in another chapter or part) get a chapter token inserted
(`MDR-ANNEX-XV-CIII-1` for chapter III, `AIACT-ANNEX-VIII-SB-1` for section B), then a numeric suffix as last resort. Uniqueness is enforced at ingest time and tested.

## Special cases and how they are handled
- **Paragraph with continuation text.** Unnumbered sub-paragraphs and lists after a numbered paragraph
  (e.g. MDR Art. 10(4), second sentence block) belong to that paragraph.
- **Articles without numbered paragraphs** (30 in the MDR, 17 in the GDPR, 19 in the AI Act): one chunk per article.
  Exception: articles titled "Definitions" (MDR Art. 2, GDPR Art. 4, AI Act Art. 3) become one chunk per
  defined term; the lead-in sentence ("the following definitions apply") is dropped.
- **Enumerations** (a), (b), (c) and dashes are kept inside the chunk as lines, nested ones indented by two spaces.
- **Long chunks.** Limit 2000 characters (about 450 tokens, fits common embedding models). Longer chunks
  are split at line boundaries (sentence boundaries for a single oversized line) into `-s1`, `-s2` ...
  If the first line is a lead-in ending in `:`, it is repeated at the start of every later part.
- **Annexes** are split along their headings: one chunk per numbered point (table row), or, for annexes
  like MDR Annex VIII, per heading section (one rule = one chunk). Text before the first heading becomes `intro`.
  "CHAPTER II" followed by its title is merged into one path entry.
- **Amendment articles** (MDR Art. 117 to 122, AI Act Art. 102 to 110) contain quoted text of other acts;
  it stays with the paragraph it belongs to.
- **Removed noise:** consolidation markers (`►M1 ... ◄`, `▼B`), footnote references and footnote texts, the
  annex table of contents (`anx_ES`) and images (e.g. the CE marking graphic in MDR Annex V, only the
  surrounding text remains).
- **Not parsed:** the preamble citations ("Having regard to ..."), chapter headings of the main body and the
  final signature block.

"""


def main() -> None:
    chunks = chunking.read_chunks()
    out = [HEAD, "## Statistics\n"]
    cnt = Counter((c.law, c.type) for c in chunks)
    out.append("| Law | Articles | Annexes | Recitals | Total |\n|---|---|---|---|---|")
    for law in ("MDR", "GDPR", "AIACT"):
        a, n, r = (cnt[(law, t)] for t in ("article", "annex", "recital"))
        out.append(f"| {law} | {a} | {n} | {r} | {a + n + r} |")
    out.append(f"| **Total** | {sum(v for (l, t), v in cnt.items() if t == 'article')} | "
               f"{sum(v for (l, t), v in cnt.items() if t == 'annex')} | "
               f"{sum(v for (l, t), v in cnt.items() if t == 'recital')} | **{len(chunks)}** |\n")
    lens = sorted(len(c.text) for c in chunks)
    q = lambda p: lens[int(p * (len(lens) - 1))]
    out.append("Text length in characters:\n")
    out.append("| min | p10 | median | p90 | p99 | max | mean |\n|---|---|---|---|---|---|---|")
    out.append(f"| {lens[0]} | {q(.1)} | {q(.5)} | {q(.9)} | {q(.99)} | {lens[-1]} | {round(statistics.mean(lens))} |\n")
    buckets = [(0, 200), (200, 500), (500, 1000), (1000, 1500), (1500, 2001)]
    out.append("| length | chunks |\n|---|---|")
    for lo, hi in buckets:
        out.append(f"| {lo} to {hi - 1} | {sum(lo <= n < hi for n in lens)} |")
    splits = sum(bool(re.search(r"-s\d+$", c.id)) for c in chunks)
    out.append(f"\nChunks that are parts of a split paragraph: {splits}. Chunks under 40 characters: "
               f"{sum(n < 40 for n in lens)} (headings without body, e.g. `MDR-ANNEX-XV-3.8`, or one-sentence paragraphs).\n")
    out.append("## 15 random samples (seed 42)\n")
    rng = random.Random(42)
    for c in rng.sample(chunks, 15):
        out.append(f"### `{c.id}`\n")
        out.append(f"- citation: {c.citation}\n- type: {c.type}, article: {c.article}, paragraph: {c.paragraph}\n- title: {c.title}\n")
        body = c.text if len(c.text) <= 700 else c.text[:700] + " [...]"
        out.append("```text\n" + body + "\n```\n")
    DOC.write_text("\n".join(out), encoding="utf-8")
    print("wrote", DOC)


if __name__ == "__main__":
    main()
